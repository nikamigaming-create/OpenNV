    public static bool TryGetBlock(ushort blockId, out FalloutCompiledBlockMetadata metadata)
    {
        if (blockId < Blocks.Length)
        {
            metadata = Blocks[blockId];
            return true;
        }
        metadata = default;
        return false;
    }

    public static bool TryGetCommand(ushort opcode, out FalloutCompiledCommandMetadata metadata)
    {
        if (opcode >= 0x0100 && opcode - 0x0100 < ConsoleCommands.Length)
        {
            metadata = ConsoleCommands[opcode - 0x0100];
            return metadata.Name.Length != 0;
        }
        if (opcode >= 0x1000 && opcode - 0x1000 < ScriptCommands.Length)
        {
            metadata = ScriptCommands[opcode - 0x1000];
            return metadata.Name.Length != 0;
        }
        metadata = default;
        return false;
    }

    public static bool TryGetAnimationGroupName(ushort groupIndex, out string name)
    {
        if (groupIndex < AnimationGroupNames.Length)
        {
            name = AnimationGroupNames[groupIndex];
            return true;
        }
        name = string.Empty;
        return false;
    }
