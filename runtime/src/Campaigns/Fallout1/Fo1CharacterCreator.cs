    private void UpdateCreatorNumbers()
    {
        var canvas = Image.CreateEmpty(Fo1CharacterCreatorNumericContracts.SourcePresentationInt640, Fo1CharacterCreatorNumericContracts.SourcePresentationInt480, false, Image.Format.Rgba8);
        canvas.BlitRect(
            _creatorChromeImage,
            new Rect2I(0, 0, Fo1CharacterCreatorNumericContracts.SourcePresentationInt640, Fo1CharacterCreatorNumericContracts.SourcePresentationInt480),
            Vector2I.Zero);
        for (var index = 0; index < _stats.Length; index++)
            DrawCreatorNumber(
                canvas,
                _stats[index],
                _contract.CreatorNumbers.Layout.Special[index],
                _contract.CreatorNumbers.SpecialDigitStride);

        var points = Math.Clamp(PointsRemaining, 0, Fo1CharacterCreatorNumericContracts.SourcePresentationInt99);
        var pointDigits = new[] { points / Fo1CharacterCreatorNumericContracts.SourcePresentationInt10, points % Fo1CharacterCreatorNumericContracts.SourcePresentationInt10 };
        for (var index = 0; index < pointDigits.Length; index++)
            DrawCreatorDigit(
                canvas,
                pointDigits[index],
                _contract.CreatorNumbers.Layout.CharacterPoints[index]);
        _creatorChromeTexture.Update(canvas);
    }

    private void DrawCreatorNumber(
        Image canvas,
        int value,
        Fo1HudPoint destination,
        int digitStride)
    {
        var normalized = Math.Clamp(value, 0, Fo1CharacterCreatorNumericContracts.SourcePresentationInt99);
        DrawCreatorDigit(canvas, normalized / Fo1CharacterCreatorNumericContracts.SourcePresentationInt10, destination);
        DrawCreatorDigit(
            canvas,
            normalized % Fo1CharacterCreatorNumericContracts.SourcePresentationInt10,
            new Fo1HudPoint(
                destination.X + digitStride,
                destination.Y));
    }

    private void DrawCreatorDigit(Image canvas, int digit, Fo1HudPoint destination)
    {
        var numbers = _contract.CreatorNumbers;
        canvas.BlitRect(
            _creatorNumberAtlas,
            new Rect2I(
                numbers.WhiteOffsetX + Math.Clamp(digit, 0, Fo1CharacterCreatorNumericContracts.SourcePresentationInt9) * numbers.DigitWidth,
                0,
                numbers.DigitWidth,
                numbers.Atlas.Height),
            destination.Pixels);
    }

